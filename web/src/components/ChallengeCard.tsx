import { Check, Sparkles } from 'lucide-react'
import { useState } from 'react'
import { Link } from 'react-router-dom'
import { EXERCISE_META } from '../exercises/meta'
import { plural } from '../lib/format'
import { useChallenges, useGenerateChallenge } from '../lib/queries'
import type { Challenge, Group } from '../lib/types'
import { Avatar, Badge, Button, cx, ErrorNote, Segmented } from './ui'

function daysLeft(c: Challenge): string {
  const ms = new Date(c.endsAt).getTime() - Date.now()
  if (ms <= 0) return 'Ended'
  const d = Math.ceil(ms / 86_400_000)
  return d === 1 ? 'Last day' : `${d} days left`
}

function SourceBadge({ c }: { c: Challenge }) {
  return c.source === 'gemini' ? (
    <Badge tone="ai">
      <Sparkles className="size-3" aria-hidden /> Generated by Gemini
    </Badge>
  ) : (
    <Badge>Set from your group's activity</Badge>
  )
}

function ProgressBar({ c }: { c: Challenge }) {
  return (
    <div>
      <div className="flex items-end justify-between">
        <span className="font-display text-4xl leading-none font-bold tabular">
          {c.progressReps.toLocaleString()}
          <span className="ml-1 font-sans text-sm font-normal text-mist">
            / {c.goalReps.toLocaleString()} {EXERCISE_META[c.exercise]?.plural ?? 'reps'}
          </span>
        </span>
        <span className="text-sm text-mist">{daysLeft(c)}</span>
      </div>
      <div className="mt-2 h-3 overflow-hidden rounded-full bg-ink/60" role="progressbar" aria-valuenow={Math.round(c.progress * 100)} aria-valuemin={0} aria-valuemax={100}>
        <div className="h-full rounded-full bg-go transition-[width] duration-700" style={{ width: `${Math.max(2, c.progress * 100)}%` }} />
      </div>
    </div>
  )
}

/** Compact version for the feed. */
export function ChallengeStrip({ group }: { group: Group }) {
  const q = useChallenges(group.id)
  const c = q.data?.find((x) => x.active)
  if (!c) return null
  return (
    <Link to={`/groups/${group.id}`} className="block rounded-[var(--radius-card)] bg-court p-4 ring-1 ring-go/30 hover:ring-go/60">
      <p className="text-sm text-mist">Shared goal in {group.name}</p>
      <h3 className="mt-0.5 mb-3 font-semibold">{c.title}</h3>
      <ProgressBar c={c} />
      <p className="mt-2 text-sm text-mist">
        {c.membersParticipating} of {plural(c.memberCount, 'member')} have chipped in
      </p>
    </Link>
  )
}

/** Full card for the group page, with the AI generator for owners and admins. */
export function ChallengeCard({ group }: { group: Group }) {
  const q = useChallenges(group.id)
  const gen = useGenerateChallenge(group.id)
  const [difficulty, setDifficulty] = useState<'easy' | 'moderate' | 'hard'>('moderate')
  const [days, setDays] = useState<'5' | '7' | '14'>('7')
  const [exercise, setExercise] = useState<'pushup' | 'squat'>('pushup')
  const [composing, setComposing] = useState(false)
  const canManage = group.myRole !== 'member'
  const c = q.data?.find((x) => x.active)

  const generator = canManage && (composing || !c) && (
    <div className="rounded-2xl bg-ink/50 p-4">
      <h4 className="font-semibold">Generate a shared challenge</h4>
      <p className="mt-1 text-sm text-mist">
        Gemini looks at your group's recent totals (numbers only — no names) and proposes a goal everyone can contribute
        to.
      </p>
      <div className="mt-3 flex flex-wrap gap-2">
        <Segmented
          label="Exercise"
          value={exercise}
          onChange={setExercise}
          options={[
            { value: 'pushup', label: 'Push-ups' },
            { value: 'squat', label: 'Squats' },
          ]}
        />
        <Segmented
          label="Difficulty"
          value={difficulty}
          onChange={setDifficulty}
          options={[
            { value: 'easy', label: 'Easy' },
            { value: 'moderate', label: 'Moderate' },
            { value: 'hard', label: 'Hard' },
          ]}
        />
        <Segmented
          label="Length"
          value={days}
          onChange={setDays}
          options={[
            { value: '5', label: '5 days' },
            { value: '7', label: '1 week' },
            { value: '14', label: '2 weeks' },
          ]}
        />
      </div>
      {gen.isError && (
        <div className="mt-3">
          <ErrorNote error={gen.error} />
        </div>
      )}
      <div className="mt-4 flex gap-2">
        <Button
          onClick={() => gen.mutate({ difficulty, days: Number(days), exercise }, { onSuccess: () => setComposing(false) })}
          loading={gen.isPending}
        >
          <Sparkles className="size-4" aria-hidden /> {c ? 'Replace current challenge' : 'Generate challenge'}
        </Button>
        {composing && (
          <Button variant="ghost" onClick={() => setComposing(false)}>
            Cancel
          </Button>
        )}
      </div>
    </div>
  )

  if (q.isPending) return null
  if (!c) {
    return (
      <section className="rounded-[var(--radius-card)] bg-court p-4">
        <h3 className="font-display text-2xl font-bold">Shared goal</h3>
        {generator || <p className="mt-1 text-sm text-mist">No challenge running. Ask a group admin to start one.</p>}
      </section>
    )
  }

  return (
    <section className="rounded-[var(--radius-card)] bg-court p-4 ring-1 ring-go/30">
      <div className="flex flex-wrap items-center gap-2">
        <SourceBadge c={c} />
        <Badge>{c.difficulty}</Badge>
      </div>
      <h3 className="mt-2 font-display text-3xl leading-none font-bold tracking-tight">{c.title}</h3>
      <p className="mt-2 text-[15px] text-mist">{c.description}</p>
      <div className="mt-4">
        <ProgressBar c={c} />
      </div>
      <p className="mt-3 text-sm">
        <strong className="tabular">{c.membersMetMinimum}</strong> of {c.memberCount} members have done{' '}
        {plural(c.minSessionsPerMember, 'session')} so far
      </p>
      <ul className="mt-3 grid grid-cols-2 gap-2 sm:grid-cols-3">
        {c.contributors.map((p) => (
          <li key={p.user.id} className="flex items-center gap-2 rounded-xl bg-ink/40 px-2 py-1.5">
            <Avatar user={p.user} size={28} />
            <div className="min-w-0 flex-1">
              <p className="truncate text-sm">{p.user.displayName.split(' ')[0]}</p>
              <p className="text-xs text-mist tabular">
                {p.reps} {EXERCISE_META[c.exercise]?.plural ?? 'reps'}
              </p>
            </div>
            {p.metMinimum && <Check className="size-4 text-go" aria-label="Met the session goal" />}
          </li>
        ))}
      </ul>
      {c.rationale && (
        <p className={cx('mt-3 text-xs', c.source === 'gemini' ? 'text-sky' : 'text-dim')}>
          {c.source === 'gemini' ? 'Why this goal (AI): ' : ''}
          {c.rationale}
        </p>
      )}
      {canManage && !composing && (
        <Button variant="ghost" size="sm" className="mt-3 -ml-2" onClick={() => setComposing(true)}>
          <Sparkles className="size-4" aria-hidden /> New challenge
        </Button>
      )}
      {composing && <div className="mt-3">{generator}</div>}
    </section>
  )
}
